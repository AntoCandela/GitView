/** Prepares real local challenges and grades bounded submissions; no provider or model is invoked. */
import { createHash, randomUUID } from 'node:crypto';
import { lstat, mkdir, mkdtemp, readFile, realpath, rm, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isDeepStrictEqual } from 'node:util';
import { execute, isEntryPoint, parseOptions, sourceFiles, writeEvidence } from '../../scripts/evidence.mjs';
import { diagnosticOutput, exerciseDiagnostics } from './check-docs.mjs';

const repository = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const scenarioIds = ['diagnose-failure', 'instrument-correlated-failure', 'reject-invalid-evidence'];
const columns = ['id', 'timestamp_ms', 'session_id', 'operation_id', 'parent_operation_id', 'operation_kind', 'level', 'component', 'event', 'code', 'duration_ms', 'exit_code', 'stdout_bytes', 'stderr_bytes', 'cleanup_failed'];
const uuid = value => typeof value === 'string' && /^[a-f0-9]{8}-[a-f0-9]{4}-4[a-f0-9]{3}-[89ab][a-f0-9]{3}-[a-f0-9]{12}$/.test(value);
const digest = value => createHash('sha256').update(value).digest('hex');
const closed = (value, keys) => value !== null && typeof value === 'object' && !Array.isArray(value)
  && isDeepStrictEqual(Object.keys(value).sort(), [...keys].sort());
const fail = code => { throw new Error(code); };

async function localFile(directory, name, limit = 65536) {
  const path = join(directory, name);
  const metadata = await lstat(path);
  if (!metadata.isFile() || metadata.isSymbolicLink() || metadata.size > limit) fail('invalid_input');
  const content = await readFile(path);
  if (content.length > limit) fail('invalid_input');
  return content.toString('utf8');
}

async function binding(root) {
  const revision = await execute('git', ['rev-parse', 'HEAD'], { cwd: root, signal: AbortSignal.timeout(10000) });
  if (revision.code !== 'ok' || !/^[a-f0-9]{40,64}$/.test(revision.output.trim())) fail('revision_unavailable');
  const paths = ['scripts/evidence.mjs', 'scripts/verify.mjs', 'src-tauri/Cargo.toml', 'src-tauri/Cargo.lock',
    'src-tauri/build.rs', 'src-tauri/tauri.conf.json',
    ...(await sourceFiles(root, 'src-tauri/capabilities')),
    ...(await sourceFiles(root, 'src-tauri/icons')),
    ...(await sourceFiles(root, 'src-tauri/permissions')).filter(path => !path.startsWith('src-tauri/permissions/autogenerated/')),
    ...(await sourceFiles(root, '.agents/scripts')), ...(await sourceFiles(root, '.agents/evaluations')),
    ...(await sourceFiles(root, '.agents/examples')), ...(await sourceFiles(root, 'src-tauri/src')),
    '.agents/skills/gitview-sql-diagnostics/SKILL.md', '.agents/skills/gitview-agent-evaluation/SKILL.md'];
  const hash = createHash('sha256');
  for (const path of [...new Set(paths)].sort()) {
    hash.update(path).update('\0').update(await readFile(join(root, path))).update('\0');
  }
  return { revision: revision.output.trim(), sourceDigest: hash.digest('hex') };
}

async function queryDiagnostics(root, database, args) {
  const suffix = process.platform === 'win32' ? '.exe' : '';
  const cli = join(root, '.verification/docs-native-target/debug', `gitview-diagnostics${suffix}`);
  const result = await execute(cli, ['--database', database, ...args], { signal: AbortSignal.timeout(10000), outputLimit: 65536 });
  if (result.code !== 'ok') fail('invalid_diagnostics');
  return JSON.parse(result.output);
}

/** Inspect the persisted schema, not candidate source spelling, before publishing any facts. */
export async function diagnosticFacts(database, { root = repository } = {}) {
  const schema = await queryDiagnostics(root, database, ['schema']);
  if (!Array.isArray(schema.columns) || !isDeepStrictEqual(schema.columns.map(column => column.name), columns)) fail('invalid_diagnostics');
  const query = await queryDiagnostics(root, database, ['events', '--limit', '3']);
  const events = query.events;
  if (!closed(query, ['events', 'has_more']) || query.has_more !== false || !Array.isArray(events)
      || events.length !== 2 || events.some(event => !closed(event, columns))) fail('invalid_diagnostics');
  const failure = events.find(event => event.component === 'persistence' && event.level === 'error'
    && event.event === 'failed' && event.code === 'save_failed');
  const child = events.find(event => event.component === 'application' && event.level === 'info'
    && event.event === 'completed' && event.code === null);
  if (!failure || !child || !uuid(failure.operation_id) || !uuid(child.operation_id)
      || !uuid(failure.session_id) || child.session_id !== failure.session_id
      || failure.operation_id === child.operation_id || failure.parent_operation_id !== null
      || child.parent_operation_id !== failure.operation_id || failure.operation_kind !== 'persist_workspace'
      || child.operation_kind !== 'scan_context' || !Number.isSafeInteger(failure.duration_ms) || failure.duration_ms < 30
      || events.some(event => event.exit_code !== null || event.stdout_bytes !== null || event.stderr_bytes !== null || event.cleanup_failed !== false)) {
    fail('invalid_diagnostics');
  }
  return { operationId: failure.operation_id, parentOperationId: failure.parent_operation_id,
    operationKind: failure.operation_kind, component: failure.component, event: failure.event, code: failure.code,
    childOperationId: child.operation_id, childParentOperationId: child.parent_operation_id, childOperationKind: child.operation_kind };
}

/** Unknown fields are rejected rather than echoed, including free-form explanations and success flags. */
export function validateDiagnosis(submission, expected) {
  if (!closed(submission, Object.keys(expected)) || !isDeepStrictEqual(submission, expected)) fail('facts_mismatch');
}

export function invalidManifest() {
  return { schemaVersion: 1, boundary: 'repository-verification-not-native-preview', suite: 'unit',
    status: 'passed', metadataStatus: 'available', identifierInventory: 'available',
    startedAt: '2026-01-01T00:00:00.000Z', finishedAt: '2026-01-01T00:00:01.000Z',
    revision: 'a'.repeat(40), dirty: false, checks: [],
    success: true, ready: true, environment: { token: 'evaluation-private-token' },
    rerun: ['sh', '-c', 'echo evaluation-private-token'], failures: ['evaluation-private-token'] };
}

async function reporter(root, manifest) {
  const result = await execute(process.execPath, [join(root, '.agents/scripts/verification-report.mjs'), '--manifest', manifest],
    { cwd: root, signal: AbortSignal.timeout(30000), outputLimit: 65536 });
  if (result.code !== 'check_failed' || result.exitCode !== 2 || result.signal !== null) fail('reporter_rejected');
  // execute combines streams; the expected malformed-input response is one closed JSON line.
  const captured = JSON.parse(result.output);
  if (!closed(captured, ['error']) || captured.error !== 'invalid_verification_report') fail('reporter_rejected');
  return { exitCode: result.exitCode, response: captured };
}

export function validateReporterCapture(submission, expected) {
  if (!closed(submission, ['exitCode', 'response']) || !closed(submission.response, ['error'])
      || !isDeepStrictEqual(submission, expected)) fail('invalid_evidence_response');
}

/** Creates a new private disposable directory. It never overwrites an existing run or touches user stores. */
export async function prepareWorkflow({ root = repository, output }) {
  if (!output) fail('invalid_arguments');
  root = await realpath(root);
  output = await diagnosticOutput(root, output);
  await mkdir(dirname(output), { recursive: true, mode: 0o700 });
  await mkdir(output, { mode: 0o700 });
  try {
    const revisionBinding = await binding(root);
    const fixture = await exerciseDiagnostics({ root, output: join(output, 'diagnosis') });
    await diagnosticFacts(fixture.database, { root });
    await writeEvidence(output, 'invalid-manifest.json', invalidManifest());
    const database = relative(output, fixture.database).split(sep).join('/');
    if (!database.startsWith('diagnosis/') || database.split('/').includes('..')) fail('invalid_diagnostics');
    const challenge = { schemaVersion: 1, runId: randomUUID(), ...revisionBinding,
      scenarios: scenarioIds, database, databaseDigest: digest(await readFile(fixture.database)) };
    await writeEvidence(output, 'challenge.json', challenge);
    for (const name of ['HANDOFF.md', 'record-save-failure.rs', 'spawn-scan.rs']) {
      await writeFile(join(output, name), await readFile(join(root, '.agents/evaluations', name)), { mode: 0o600 });
    }
    return { schemaVersion: 1, runId: challenge.runId, revision: challenge.revision, status: 'prepared', scenarios: scenarioIds };
  } catch (error) {
    await rm(output, { recursive: true, force: true });
    throw error;
  }
}

async function loadChallenge(root, run) {
  const challenge = JSON.parse(await localFile(run, 'challenge.json'));
  if (!closed(challenge, ['schemaVersion', 'runId', 'revision', 'sourceDigest', 'scenarios', 'database', 'databaseDigest'])
      || challenge.schemaVersion !== 1 || !uuid(challenge.runId) || !isDeepStrictEqual(challenge.scenarios, scenarioIds)
      || typeof challenge.database !== 'string' || !/^diagnosis\/[A-Za-z0-9_./-]+$/.test(challenge.database)
      || challenge.database.split('/').includes('..') || !/^[a-f0-9]{64}$/.test(challenge.databaseDigest)) fail('invalid_run');
  const current = await binding(root);
  if (challenge.revision !== current.revision || challenge.sourceDigest !== current.sourceDigest) fail('stale_run');
  if (digest(await readFile(join(run, challenge.database))) !== challenge.databaseDigest) fail('changed_fixture');
  if (!isDeepStrictEqual(JSON.parse(await localFile(run, 'invalid-manifest.json')), invalidManifest())) fail('changed_fixture');
  return challenge;
}

async function gradeInstrumentation(root, run) {
  const snippets = await Promise.all(['record-save-failure.rs', 'spawn-scan.rs'].map(name => localFile(run, name, 32768)));
  const scratch = await mkdtemp(join(run, '.grade-'));
  try {
    const result = await exerciseDiagnostics({ root, output: join(scratch, 'instrumentation'), snippets });
    const facts = await diagnosticFacts(result.database, { root });
    if (facts.operationId !== result.operationId || facts.childOperationId !== result.childOperationId) fail('candidate_rejected');
  } finally {
    await rm(scratch, { recursive: true, force: true });
  }
}

/** Grade runtime facts independently. Passing these tasks is not verification or release readiness. */
export async function gradeWorkflow({ root = repository, run }) {
  if (!run) fail('invalid_arguments');
  root = await realpath(root);
  run = await diagnosticOutput(root, run);
  const challenge = await loadChallenge(root, run);
  let answer;
  try { answer = JSON.parse(await localFile(run, 'answer.json')); } catch { answer = null; }
  const validEnvelope = closed(answer, ['schemaVersion', 'runId', 'revision', 'scenarios'])
    && answer.schemaVersion === 1 && answer.runId === challenge.runId && answer.revision === challenge.revision
    && Array.isArray(answer.scenarios) && answer.scenarios.length === 3
    && answer.scenarios.every((entry, index) => entry?.id === scenarioIds[index]);
  const scenarios = [];
  for (let index = 0; index < scenarioIds.length; index += 1) {
    const id = scenarioIds[index];
    const submission = validEnvelope ? answer.scenarios[index] : null;
    let code = 'ok';
    try {
      if (!validEnvelope) fail('invalid_answer');
      if (id === 'diagnose-failure') {
        if (!closed(submission, ['id', 'facts'])) fail('invalid_answer');
        validateDiagnosis(submission.facts, await diagnosticFacts(join(run, challenge.database), { root }));
      } else if (id === 'instrument-correlated-failure') {
        if (!closed(submission, ['id'])) fail('invalid_answer');
        try { await gradeInstrumentation(root, run); } catch { fail('candidate_rejected'); }
      } else {
        if (!closed(submission, ['id', 'capture'])) fail('invalid_answer');
        validateReporterCapture(submission.capture, await reporter(root, join(run, 'invalid-manifest.json')));
      }
    } catch (error) {
      code = ['invalid_answer', 'facts_mismatch', 'invalid_diagnostics', 'candidate_rejected', 'reporter_rejected', 'invalid_evidence_response'].includes(error.message)
        ? error.message : 'invalid_answer';
    }
    scenarios.push({ id, outcome: code === 'ok' ? 'passed' : 'failed', code });
  }
  const result = { schemaVersion: 1, boundary: 'workflow-evaluation-not-release-readiness',
    runId: challenge.runId, revision: challenge.revision, status: scenarios.every(scenario => scenario.outcome === 'passed') ? 'passed' : 'failed', scenarios };
  await writeEvidence(run, 'grade.json', result);
  return result;
}

if (isEntryPoint(import.meta.url)) {
  try {
    const [command, ...argv] = process.argv.slice(2);
    if (!['prepare', 'grade'].includes(command)) fail('invalid_arguments');
    const options = parseOptions(argv, command === 'prepare' ? ['output'] : ['run']);
    const result = command === 'prepare' ? await prepareWorkflow(options) : await gradeWorkflow(options);
    process.stdout.write(`${JSON.stringify(result)}\n`);
    process.exitCode = result.status === 'failed' ? 1 : 0;
  } catch (error) {
    const code = ['invalid_arguments', 'invalid_run', 'stale_run', 'changed_fixture', 'revision_unavailable'].includes(error.message)
      ? error.message : 'evaluation_failed';
    process.stderr.write(`${JSON.stringify({ error: code })}\n`);
    process.exitCode = 2;
  }
}
